/** Union of all translation keys (derived from the `en` set) for compile-time safety. */
export type TranslationKey = keyof typeof TRANSLATIONS.en;

/** Option entry for the GUI-locale select (value + localized label + desc). */
export interface LocaleOption {
    value: string;
    label: string;
    desc?: string;
}

/**
 * Resolves the effective GUI locale from the `gui.locale` setting.
 *
 * `auto` (or an unknown value) resolves via `detectLocale`; an unknown detected locale falls
 * back to `en` (GUI fallback), not `de` (content fallback).
 *
 * @param setting - The raw `gui.locale` value ("auto" | "de" | "en" | other).
 * @returns The resolved GUI locale.
 */
function resolveGuiLocale(setting: string): GuiLocale {
    if (setting === "de") return "de";
    if (setting === "en") return "en";
    // * auto (or invalid): detectLocale returns "de"|"en" for known YT languages,
    //   otherwise "de" (content fallback). For the GUI we use en as fallback for unknown.
    const detected = detectLocale();
    if (detected === "de" || detected === "en") return detected;
    return "en";
}

// * Reactive effLocale — reads gui.locale from the store via $derived.
const effLocale = $derived(resolveGuiLocale(String(store.getByPath("gui.locale") ?? "auto")));

// * t(key): reactive to gui.locale changes. Fallback: en → key string.
/**
 * Returns the localized string for a translation key, reactive to `gui.locale`.
 *
 * Falls back to `en`, then to the raw key string if both are absent. Optional
 * `params` interpolate `{placeholders}` in the resolved string (e.g. `{n}`).
 *
 * @param key    - The translation key.
 * @param params - Optional placeholder values.
 * @returns The localized, interpolated string.
 */
export function t(key: TranslationKey, params?: Record<string, string | number>): string {
    const raw = TRANSLATIONS[effLocale][key] ?? TRANSLATIONS.en[key] ?? key;
    if (!params) return raw;
    return raw.replace(/\{(\w+)\}/g, (m, p: string) => (p in params ? String(params[p]) : m));
}

/**
 * Returns the locale select options (auto/de/en) with localized labels.
 *
 * @returns The locale option list.
 */
export function getLocaleOptions(): LocaleOption[] {
    return [
        { value: "auto", label: "Auto", desc: t("optdesc.localeAuto") },
        { value: "de", label: "Deutsch", desc: t("optdesc.localeDe") },
        { value: "en", label: "English", desc: t("optdesc.localeEn") },
    ];
}
